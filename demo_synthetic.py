"""
End-to-end test of the pipeline on SYNTHETIC data generated by the model itself.

This is a validation step, not a result: it checks that (1) the two-stage fit
recovers known parameters, (2) which parameters the zero-field data can and
cannot separate, and (3) whether field data can discriminate between the two
population factors used in the literature. Replace with digitised published
data for the real analysis (see data/README.md).
"""
import numpy as np
import matplotlib.pyplot as plt

from callaway_cef import kappa, kappa_data, LevelScheme, Multiplet
from fit import fit_kappa, report

rng = np.random.default_rng(0)
NOISE = 0.04  # 4 % multiplicative noise, typical of digitised log-log plots

# ---- "true" parameters (Tb2Ti2O7-like orders of magnitude, NOT literature values)
lattice = dict(v=3500.0, thetaD=350.0, b=4.0, L=3e-4, A=1.5e3, B=1.0e6)
true_res = dict(C_0_0=3e9, C_0_1=3e10, E1=18.0)
SITES_111 = [(0.25, 1.0), (0.75, 1 / 3)]          # H || [111] on the pyrochlore lattice


def make_scheme(population="difference"):
    return LevelScheme(
        multiplets=[Multiplet(E0=0.0, deg=2, delta=1.5, m=5.0),    # ground quasi-doublet
                    Multiplet(E0=18.0, deg=2, delta=0.0, m=3.0)],  # first excited doublet
        transitions=[(0, 0), (0, 1)], sites=SITES_111, population=population)


scheme = make_scheme()
p_true = {**lattice, **true_res}
noisy = lambda k: k * np.exp(NOISE * rng.standard_normal(k.shape))

T = np.logspace(np.log10(0.3), np.log10(60), 30)
k_ref = noisy(kappa(T, 0, lattice))
k_tb0 = noisy(kappa(T, 0, p_true, scheme))
fields = [0, 1, 2, 5, 9]
k_tbH = {H: noisy(kappa(T, H, p_true, scheme)) for H in fields}

# ---- stage 1: non-magnetic analogue -> lattice terms
print("STAGE 1  reference compound (no resonant term)")
p0 = dict(v=3500.0, thetaD=350.0, b=4.0, L=1e-4, A=1e2, B=1e5)
free1 = ["L", "A", "B"]
p_lat, e1, c1, r1 = fit_kappa(T, k_ref, np.zeros_like(T), p0, free1)
report(free1, p_lat, e1, c1, r1, len(T))

# ---- stage 2: Tb compound at H = 0, lattice fixed
print("\nSTAGE 2  magnetic compound, H = 0 (lattice terms fixed)")
free2 = ["C_0_0", "C_0_1", "E1"]
bounds2 = {"E1": (12.0, 24.0)}      # in a real fit: neutron CEF value +- its uncertainty
p0 = {**p_lat, "C_0_0": 1e8, "C_0_1": 1e9, "E1": 15.0}
p_fit, e2, c2, r2 = fit_kappa(T, k_tb0, np.zeros_like(T), p0, free2, scheme, bounds2)
report(free2, p_fit, e2, c2, r2, len(T))
print("  true:", {k: v for k, v in true_res.items()})

# ---- stage 2b: same zero-field data, other population factor
print("\nSTAGE 2b same H = 0 data fitted with population = 'sum'")
scheme_sum = make_scheme("sum")
p_sum, e2b, c2b, r2b = fit_kappa(T, k_tb0, np.zeros_like(T), p0, free2, scheme_sum, bounds2)
report(free2, p_sum, e2b, c2b, r2b, len(T))

# ---- stage 3: field predictions, zero new parameters
print("\nSTAGE 3  prediction of kappa(T, H) from the H = 0 fits (no new parameter)")
for name, sch, p in [("difference", scheme, p_fit), ("sum", scheme_sum, p_sum)]:
    allT = np.concatenate([T for _ in fields])
    allH = np.concatenate([np.full_like(T, H) for H in fields])
    allk = np.concatenate([k_tbH[H] for H in fields])
    rms = np.sqrt(np.mean((np.log(kappa_data(allT, allH, p, sch)) - np.log(allk)) ** 2))
    print(f"  population = {name:10s}: rms log-residual on field data = {rms:.3f}")

# ---------------------------------------------------------------- figures
Tf = np.logspace(np.log10(0.3), np.log10(60), 200)
cols = plt.cm.viridis(np.linspace(0, 0.9, len(fields)))
fig, ax = plt.subplots(1, 3, figsize=(15, 4.6))

a = ax[0]
a.loglog(T, k_ref, "o", mfc="none", c="0.4", label="reference (synthetic)")
a.loglog(Tf, kappa(Tf, 0, p_lat), c="0.4")
a.loglog(T, k_tb0, "o", c="C3", label="Tb compound, H = 0 (synthetic)")
a.loglog(Tf, kappa(Tf, 0, p_fit, scheme), c="C3", label="fit, F = p$_l$ − p$_u$")
a.loglog(Tf, kappa(Tf, 0, p_sum, scheme_sum), "--", c="C1", label="fit, F = p$_l$ + p$_u$")
a.set(xlabel="T (K)", ylabel="κ (W m$^{-1}$ K$^{-1}$)", title="Stages 1–2: zero-field fits")
a.legend(fontsize=8)

a = ax[1]
for H, c in zip(fields, cols):
    a.loglog(T, k_tbH[H], "o", ms=4, c=c)
    a.loglog(Tf, kappa(Tf, H, p_fit, scheme), c=c, label=f"{H} T")
    a.loglog(Tf, kappa(Tf, H, p_sum, scheme_sum), ":", c=c)
a.set(xlabel="T (K)", ylabel="κ (W m$^{-1}$ K$^{-1}$)",
      title="Stage 3: predicted κ(T, H)  (solid: difference, dotted: sum)")
a.legend(fontsize=8, title="H ∥ [111]")

a = ax[2]
Hs = np.linspace(0, 9, 91)
for Tfix, c in zip([0.5, 2, 5, 10, 15], plt.cm.plasma(np.linspace(0, 0.85, 5))):
    k0 = kappa(Tfix, 0, p_fit, scheme)[0]
    a.plot(Hs, [kappa(Tfix, h, p_fit, scheme)[0] / k0 for h in Hs], c=c, label=f"{Tfix} K")
a.set_yscale("log")
a.axhline(1, c="0.6", lw=0.8)
a.set(xlabel="μ$_0$H (T)", ylabel="κ(H) / κ(0)", title="Magnetothermal conductivity")
a.legend(fontsize=8)

for a in ax:
    a.spines[["top", "right"]].set_visible(False)
plt.tight_layout()
plt.savefig("figures/demo_synthetic.png", dpi=150, bbox_inches="tight")

# scattering-rate decomposition at one temperature, two fields
fig, ax = plt.subplots(1, 2, figsize=(10, 4), sharey=True)
for a, H in zip(ax, [0, 5]):
    _, x, w, rates = kappa(np.array([2.0]), H, p_fit, scheme, return_rates=True)
    for name, r in rates.items():
        a.loglog(w[0], r[0], label=name)
    a.set(xlabel="phonon energy ħω/k$_B$ (K)", title=f"T = 2 K, H = {H} T", ylim=(1e5, 1e13))
    a.spines[["top", "right"]].set_visible(False)
ax[0].set_ylabel("1/τ (s$^{-1}$)")
ax[0].legend(fontsize=8)
plt.tight_layout()
plt.savefig("figures/demo_rates.png", dpi=150, bbox_inches="tight")
print("\nfigures written to figures/")
